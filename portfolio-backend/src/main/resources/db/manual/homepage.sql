CREATE TABLE IF NOT EXISTS homepage_translations (
    language varchar(2) PRIMARY KEY CHECK (language IN ('zh', 'en', 'ja')),
    desc1 text NOT NULL,
    desc2 text NOT NULL,
    contact_public text NOT NULL,
    contact_prof text NOT NULL
);
CREATE TABLE IF NOT EXISTS homepage_quotes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content varchar(500) NOT NULL,
    source varchar(120) NOT NULL DEFAULT '',
    language varchar(2) CHECK (language IS NULL OR language IN ('zh', 'en', 'ja')),
    enabled boolean NOT NULL DEFAULT true
);
-- Exactly one identity is valid. The primary key and CHECK together cap this table at one row.
CREATE TABLE IF NOT EXISTS homepage_listening (
    id bigint PRIMARY KEY CONSTRAINT homepage_listening_singleton CHECK (id = 1),
    artist varchar(120) NOT NULL DEFAULT '',
    title varchar(200) NOT NULL DEFAULT '',
    url varchar(2000) NOT NULL DEFAULT '',
    enabled boolean NOT NULL DEFAULT false
);

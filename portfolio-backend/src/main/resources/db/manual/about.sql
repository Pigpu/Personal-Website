-- Additive and repeatable. Existing homepage and other site data are untouched.
BEGIN;
CREATE TABLE IF NOT EXISTS about_translations (
    language varchar(2) PRIMARY KEY CHECK (language IN ('zh', 'en', 'ja')),
    title varchar(120) NOT NULL,
    purpose1 text NOT NULL,
    purpose2 text NOT NULL
);
CREATE TABLE IF NOT EXISTS friend_links (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL,
    url varchar(2000) NOT NULL,
    description varchar(500) NOT NULL DEFAULT ''
);
COMMIT;

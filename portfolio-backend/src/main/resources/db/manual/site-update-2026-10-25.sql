-- Personal Website: database preparation for the 2026-10-25 redesign.
-- PostgreSQL (the project's development version is 16).
-- Run this ENTIRE file in the website's database, using a role allowed to create tables.
-- Existing business tables and content are not modified or deleted.
-- Repeatable: existing tables are skipped and the current song is never overwritten.
-- IF NOT EXISTS does not repair a table with a different structure; inspect any existing names first.
-- This does not copy the content entered in the local development database to production.

BEGIN;
SET LOCAL search_path TO public;

-- 1. Homepage introduction and contact text, maintained separately in three languages.
CREATE TABLE IF NOT EXISTS homepage_translations (
    language varchar(2) PRIMARY KEY CHECK (language IN ('zh', 'en', 'ja')),
    desc1 text NOT NULL,
    desc2 text NOT NULL,
    contact_public text NOT NULL,
    contact_prof text NOT NULL
);

-- 2. Random quotations. NULL language means usable in all three languages.
CREATE TABLE IF NOT EXISTS homepage_quotes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content varchar(500) NOT NULL,
    source varchar(120) NOT NULL DEFAULT '',
    language varchar(2) CHECK (language IS NULL OR language IN ('zh', 'en', 'ja')),
    enabled boolean NOT NULL DEFAULT true
);

-- 3. Currently listening: at most one row. Future saves replace id=1.
CREATE TABLE IF NOT EXISTS homepage_listening (
    id bigint PRIMARY KEY CONSTRAINT homepage_listening_singleton CHECK (id = 1),
    artist varchar(120) NOT NULL DEFAULT '',
    title varchar(200) NOT NULL DEFAULT '',
    url varchar(2000) NOT NULL DEFAULT '',
    enabled boolean NOT NULL DEFAULT false
);
INSERT INTO homepage_listening (id, artist, title, url, enabled)
VALUES (1, '', '', '', false)
ON CONFLICT (id) DO NOTHING;

-- 4. Shared countdown: at most one row. Set the event and date through the admin UI after deployment.
CREATE TABLE IF NOT EXISTS homepage_countdown (
    id bigint PRIMARY KEY CONSTRAINT homepage_countdown_singleton CHECK (id = 1),
    event varchar(120) NOT NULL,
    target_date date NOT NULL
);

-- 5. About-page title and paragraphs: one row per language, updated in place.
CREATE TABLE IF NOT EXISTS about_translations (
    language varchar(2) PRIMARY KEY CHECK (language IN ('zh', 'en', 'ja')),
    title varchar(120) NOT NULL,
    purpose1 text NOT NULL,
    purpose2 text NOT NULL
);

-- 6. Friend links. Editing updates the existing row; deleting removes only that link.
CREATE TABLE IF NOT EXISTS friend_links (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL,
    url varchar(2000) NOT NULL,
    description varchar(500) NOT NULL DEFAULT ''
);

COMMIT;

-- Verification: this result should contain all six table names.
SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_name IN (
    'homepage_translations', 'homepage_quotes', 'homepage_listening',
    'homepage_countdown', 'about_translations', 'friend_links'
  )
ORDER BY table_name;
